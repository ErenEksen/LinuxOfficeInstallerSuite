//! `~/.msoffice/bin/msoffice-launch`: a POSIX shell wrapper that starts an Office app with
//! the active runner (design D6, desktop-integration: Launch wrapper). It needs nothing but
//! files under `~/.msoffice/`, so Office keeps working when this app is removed.

use std::os::unix::fs::PermissionsExt;
use std::path::Path;

use crate::core::config::write_atomic;
use crate::core::paths::Paths;
use crate::office::detect::App;
use crate::office::postinstall::LOCKER;

/// Single-quote a string for `sh`.
pub fn sh_quote(s: &str) -> String {
    format!("'{}'", s.replace('\'', "'\\''"))
}

/// Render the wrapper. `office16` is the Windows path of the `Office16` folder.
pub fn render(paths: &Paths, office16: &str) -> String {
    let mut cases = String::new();
    for app in App::ALL {
        cases.push_str(&format!("    {}) exe={} ;;\n", app.id(), app.exe()));
    }
    let ids: Vec<&str> = App::ALL.iter().map(|a| a.id()).collect();
    format!(
        r#"#!/bin/sh
# Generated by Linux Office Installer Suite. Starts an Office app in the ~/.msoffice prefix
# with the active Wine runner. Works without the installer app.
#
# usage: msoffice-launch <{ids}> [FILE...]
set -u

ROOT={root}
OFFICE16={office16}
WINE="$ROOT/runners/active/bin/wine"

export WINEPREFIX="$ROOT/prefix"
export WINEDLLOVERRIDES="winemenubuilder.exe=d"
export WINEDEBUG="${{WINEDEBUG:--all}}"
if [ -n "${{WAYLAND_DISPLAY:-}}" ]; then
    export WINE_USE_EGL=1
fi

app="${{1:-}}"
case "$app" in
{cases}    *)
        echo "usage: msoffice-launch <{ids}> [FILE...]" >&2
        exit 2 ;;
esac
shift

if [ ! -x "$WINE" ]; then
    echo "msoffice-launch: no active Wine runner in $ROOT/runners/active" >&2
    exit 1
fi

locker="$WINEPREFIX/{locker}"
if [ -e "$locker" ]; then
    chmod 0770 "$locker"
fi

# Chromium's sandbox does not work under Wine; WebView2 (used by Office features) needs this.
export WEBVIEW2_ADDITIONAL_BROWSER_ARGUMENTS="${{WEBVIEW2_ADDITIONAL_BROWSER_ARGUMENTS:---no-sandbox}}"

# Soda runners send Microsoft account sign-in to a bridge on this side, which signs in
# through the system browser. Without it, Office's Sign in button does nothing.
identity="$ROOT/bin/{helper}"
if [ -x "$identity" ] && [ -z "${{SODA_IDENTITY_BRIDGE_SOCKET:-}}" ]; then
    if socket=$("$identity" ensure); then
        export SODA_IDENTITY_BRIDGE_SOCKET="$socket"
    fi
fi

# Convert each Linux path to a Windows path. Other arguments, such as Office switches
# like /safe, pass through unchanged.
n=$#
while [ "$n" -gt 0 ]; do
    arg="$1"
    shift
    n=$((n - 1))
    case "$arg" in
        file://*) arg=$(printf '%s' "${{arg#file://}}" | sed 's/%20/ /g') ;;
    esac
    case "$arg" in
        /*)
            dir="${{arg%/*}}"
            if [ -e "$arg" ] || {{ [ -n "$dir" ] && [ -d "$dir" ]; }}; then
                arg=$("$WINE" winepath -w "$arg" 2>/dev/null)
            fi ;;
        *)
            if [ -e "$arg" ]; then
                arg=$("$WINE" winepath -w "$PWD/$arg" 2>/dev/null)
            fi ;;
    esac
    set -- "$@" "$arg"
done

exec "$WINE" "$OFFICE16\\$exe" "$@"
"#,
        ids = ids.join("|"),
        root = sh_quote(&paths.root.to_string_lossy()),
        office16 = sh_quote(office16),
        locker = LOCKER,
        helper = crate::identity::HELPER_NAME,
        cases = cases,
    )
}

/// Write the wrapper (mode 0755). It lives under `~/.msoffice/`, so it is not in the ledger.
pub fn install(paths: &Paths, office16: &str) -> std::io::Result<()> {
    let path = paths.launch_wrapper();
    write_atomic(&path, render(paths, office16).as_bytes())?;
    std::fs::set_permissions(&path, std::fs::Permissions::from_mode(0o755))
}

pub fn exists(paths: &Paths) -> bool {
    Path::new(&paths.launch_wrapper()).exists()
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::process::Command;

    const O16: &str = r"C:\Program Files\Microsoft Office\root\Office16";

    #[test]
    fn renders_every_app() {
        let paths = Paths::for_home(Path::new("/home/u"));
        let s = render(&paths, O16);
        assert!(s.starts_with("#!/bin/sh\n"));
        for app in App::ALL {
            assert!(s.contains(&format!("    {}) exe={} ;;\n", app.id(), app.exe())), "{app:?}");
        }
        assert!(s.contains("ROOT='/home/u/.msoffice'"));
        assert!(s.contains(r"OFFICE16='C:\Program Files\Microsoft Office\root\Office16'"));
        assert!(s.contains("WINE=\"$ROOT/runners/active/bin/wine\""));
        assert!(s.contains("chmod 0770 \"$locker\""));
        assert!(s.contains("winepath -w"));
        assert!(s.contains("winemenubuilder.exe=d"));
        assert!(s.contains("identity=\"$ROOT/bin/msoffice-identity\""));
        assert!(s.contains("WEBVIEW2_ADDITIONAL_BROWSER_ARGUMENTS:---no-sandbox"));
        assert!(s.contains("export SODA_IDENTITY_BRIDGE_SOCKET=\"$socket\""));
        assert!(!s.to_lowercase().contains("distrobox"));
        assert_eq!(sh_quote("it's"), r"'it'\''s'");
    }

    /// Runs the wrapper against a fake runner whose `wine` records its arguments.
    #[test]
    fn converts_paths_and_uses_the_active_runner() {
        let tmp = tempfile::tempdir().unwrap();
        let paths = Paths::for_home(tmp.path());
        paths.ensure_layout().unwrap();
        let bin = paths.runner("fake").join("bin");
        std::fs::create_dir_all(&bin).unwrap();
        let rec = tmp.path().join("rec.txt");
        let fake = format!(
            "#!/bin/sh\nif [ \"$1\" = winepath ]; then printf 'Z:%s\\n' \"$3\" | tr / '\\\\\\\\'; exit 0; fi\n\
             printf '%s\\n' \"$WINEPREFIX\" \"$@\" > {}\n",
            rec.display()
        );
        std::fs::write(bin.join("wine"), fake).unwrap();
        std::fs::set_permissions(bin.join("wine"), std::fs::Permissions::from_mode(0o755)).unwrap();
        std::os::unix::fs::symlink("fake", paths.active_runner_link()).unwrap();
        let locker = paths.prefix().join(LOCKER);
        std::fs::create_dir_all(&locker).unwrap();
        std::fs::set_permissions(&locker, std::fs::Permissions::from_mode(0o500)).unwrap();
        install(&paths, O16).unwrap();

        let doc = tmp.path().join("My Report.docx");
        std::fs::write(&doc, "x").unwrap();
        let new_file = tmp.path().join("new.docx");
        let st = Command::new(paths.launch_wrapper()).arg("word").arg(&doc).arg("/safe").arg(&new_file).status().unwrap();
        assert!(st.success());
        let out = std::fs::read_to_string(&rec).unwrap();
        let lines: Vec<&str> = out.lines().collect();
        assert_eq!(lines[0], paths.prefix().to_str().unwrap());
        assert_eq!(lines[1], format!(r"{O16}\WINWORD.EXE"));
        assert!(lines[2].starts_with("Z:\\") && lines[2].ends_with(r"\My Report.docx"), "{}", lines[2]);
        assert_eq!(lines[3], "/safe", "Office switches pass through");
        assert!(lines[4].ends_with(r"\new.docx"), "a new file in an existing folder is converted");
        assert_eq!(locker.metadata().unwrap().permissions().mode() & 0o777, 0o770);

        let st = Command::new(paths.launch_wrapper()).arg("nope").status().unwrap();
        assert_eq!(st.code(), Some(2));
    }

    #[test]
    fn shellcheck_is_clean() {
        if crate::core::proc::which("shellcheck").is_none() {
            eprintln!("shellcheck not installed; skipping");
            return;
        }
        let tmp = tempfile::tempdir().unwrap();
        let f = tmp.path().join("msoffice-launch");
        std::fs::write(&f, render(&Paths::for_home(Path::new("/home/u")), O16)).unwrap();
        let out = Command::new("shellcheck").arg("-s").arg("sh").arg(&f).output().unwrap();
        assert!(out.status.success(), "{}", String::from_utf8_lossy(&out.stdout));
    }
}
